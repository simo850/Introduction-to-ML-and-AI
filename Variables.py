# Introduction to Python Variables

# String variable
name = "Simon"

# Integer variable
age = 26

# Float variable
height = 1.75

# Boolean variable
is_student = True

# Display the variables
print("My name is:", name)
print("My age is:", age)
print("My height is:", height)
print("Am I a student?", is_student)

# Display variable data types
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))
